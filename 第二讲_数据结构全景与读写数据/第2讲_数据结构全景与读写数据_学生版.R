# 用 students.xlsx 完成下面五步，每一步一个变量，最后把 s5 存成 Excel 交上来
#
#   step 1　读入数据，做一次体检（几行几列、有无缺失）
#   step 2　只保留 姓名、性别、数学 三列
#   step 3　只保留女生
#   step 4　按数学成绩降序排列
#   step 5　取前 5 行，写出为「数学女状元.xlsx」
#
library("openxlsx")   # 读写Excel的包

# step1：读入数据，做数据体检
s1 <- read.xlsx("students.xlsx")
dim(s1)
sum(is.na(s1))

# step2：只保留 姓名、性别、数学 三列
s2 <- s1[, c("姓名","性别","数学")]

# step3：只保留女生
s3 <- s2[s2$性别 == "女", ]

# step4：按数学成绩降序排列
s4 <- s3[order(s3$数学, decreasing = TRUE), ]

# step5：取前5行，保存成Excel
s5 <- s4[1:5, ]
write.xlsx(s5, file = "数学女状元.xlsx")

