#   save   ：存「对象连同名字」，load() 后直接就叫原来的名字
# 建议：日常一律用 saveRDS，名字自己掌控，不会莫名其妙覆盖现有变量。
### 1. saveRDS / readRDS

# - 保存：**只存对象里面的数据内容，不存变量名**
#   - 读取：`a <- readRDS("x.rds")`，**必须自己赋值、自己命名**，你想叫什么变量名都可以
# - 特点：**一次只能存 1 个对象**
#   - 推荐日常优先用，不会悄无声息覆盖环境里已有的变量
# 
# ### 2. save / load
# 
# - 保存：**对象连同变量名字一起存入文件**
#   - 读取：`load("xxx.RData")`，**不需要赋值**，运行 load 后，内存里自动恢复原来的变量名
# - 特点：**一次可以同时保存多个对象**
#   - 风险：load 会直接把变量加载进环境，**可能覆盖你已经存在的同名变量**


