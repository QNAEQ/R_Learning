# ── 1.1　%>% 到底在干什么 ────────────────────────────────────────────────────────────
# 一句话：把左边的结果，当成右边函数的第一个参数塞进去。
mean(c(1, 2, 3))                  # 平常的写法
c(1, 2, 3) %>% mean()             # 管道写法，完全等价

# 快捷键：Ctrl + Shift + M。以后每天要按几十次，现在就把它按熟。

# 两大优势：大幅减少中间变量；大幅提升代码可读性。



