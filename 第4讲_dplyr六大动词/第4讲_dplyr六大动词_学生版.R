library(dplyr)
library(readxl)

竞赛包裹 <- read_excel("cb_packages.xlsx")
时长门槛 <- 18

竞赛包裹 %>%
  # 1. filter筛选：品类是数码电子/美妆护肤；通关时间>=18；申报价值或通关时间无缺失
  filter(
    商品类别 %in% c("数码电子", "美妆护肤"),
    通关时间 >= 时长门槛,
    !is.na(申报价值) | !is.na(通关时间)
  ) %>%
  # 2. mutate+ifelse：新增优先积分
  mutate(
    优先积分 = ifelse(申报价值 >= 3000, 3, 1)
  ) %>%
  # 3. group_by + summarise：口岸汇总，计算待处置数、总积分、首包编号
  group_by(入境口岸) %>%
  summarise(
    待处置数 = n(),
    总积分 = sum(优先积分),
    首包编号 = min(包裹编号),
    .groups = "drop"
  ) %>%
  # 筛选：待处置数 >=30
  filter(待处置数 >= 30) %>%
  # 4. 排序：总积分降序 → 待处置数降序 → 首包编号升序
  arrange(desc(总积分), desc(待处置数), 首包编号) %>%
  # 新增核验码
  mutate(核验码 = 总积分 * 10000 + 待处置数) %>%
  # rename + relocate：改名并把口岸移到最前面
  rename(支援口岸 = 入境口岸) %>%
  relocate(支援口岸) %>%
  # 只保留指定4列
  select(支援口岸, 待处置数, 总积分, 核验码) %>%
