BMI计算器 <- function(身高, 体重) {  
  bmi <- 体重 / (身高^2)  
  体型 <- if (bmi < 18.5) {  
    "偏瘦"  
  } else if (bmi < 24) { 
    "正常"  
  } else if (bmi < 28) {  
    "偏胖"  
  } else {  
    "肥胖"  
  }  
  paste0("BMI = ", round(bmi, 1), "，体型：", 体型)  
}  

