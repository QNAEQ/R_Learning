# 图 2　AQI 越高，PM2.5 就越高吗？—— 散点图 + 城市名标注
ggplot(aqi, aes(x = AQI均值, y = PM25均值, color = 区域)) +
  geom_point(size = 4) +
  geom_text(aes(label = 城市), vjust = -1, size = 3.5, show.legend = FALSE) +  #只控制本图层不要参与图里显示
  labs(title = "AQI 与 PM2.5 的关系", x = "AQI 均值", y = "PM2.5 均值")
# 结论很清楚：两者几乎在一条直线上。说明这批城市的 AQI 主要由 PM2.5 主导。

# 图 3　哪个区域内部差异更大？—— 箱线图
boxplot(AQI均值 ~ 区域, data = aqi, col = c("tomato", "steelblue", "forestgreen"),
        main = "各区域 AQI 分布", ylab = "AQI 均值")
# ★ 这张先用 base 快速看。geom_boxplot() 的 ggplot 版本，下一讲第 1 回合就学。





# 图 4　全年优良天数，哪个城市最宜居？
ggplot(aqi, aes(x = reorder(城市, 优良天数), y = 优良天数)) +
  geom_col(fill = "forestgreen") +
  coord_flip() +                                  # 翻转成横条，城市名不用挤着显示
  labs(title = "年度优良天数排名", x = "城市", y = "优良天数")





# 图 5　AQI 的分布是均匀的，还是集中在某个区间？—— 直方图
hist(aqi$AQI均值, breaks = 5, col = "steelblue", border = "white",
     main = "AQI 均值的分布", xlab = "AQI 均值")
