ggplot(data = mtcars) +                          # ① 数据：这张图画的是谁
  aes(x = wt, y = mpg) +                         # ② 映射：哪一列画在 x 轴，哪一列画在 y 轴
  geom_point()                                   # ③ 几何图层：用什么形状把它画出来

#彻底摆脱括号的束缚




# 本题作答与笔记区结束。

# 更常见的紧凑写法（把 aes 写进 ggplot 括号里，效果完全一样）：
ggplot(mtcars, aes(x = wt, y = mpg)) +
  geom_point()

# ⚠ 三个最常见的报错来源
#   1) 加号 + 写在了下一行的行首 —— 必须写在上一行的行尾，R 才知道话没说完
#   2) 用了 %>% 而不是 + —— 管道用来传数据，加号用来叠图层，两回事
#   3) 列名写在了引号里 —— aes(x = "wt") 会画出一个点，不是报错，更难查



# ── 2.2　「映射」到底是什么意思 ───────────────────────────────────────────────────────────
# 映射 = 把数据里的某一列，交给图上的某个视觉属性去表现。
#   x、y      → 位置
#   color     → 颜色
#   size      → 大小
#   shape     → 形状
# aes() 里面写的，永远是「哪一列对应哪个视觉属性」。



# ── 2.3　图层可以一直叠下去 ─────────────────────────────────────────────────────────────


# ┌────────────────────────────────────────────────────────────────────────────┐
# │ ★【练习 2-2】
# 本知识点例题：参数填空；按紧邻的讲解与行尾完成。
# └────────────────────────────────────────────────────────────────────────────┘
head(mtcars)


ggplot(mtcars, aes(x = wt, y = mpg)) +
  geom_point(color = "red", size = 2) +    # 第一层：散点
  geom_smooth(method = "lm", formula = y ~ x,    # 第二层：一条线性拟合线
              se = FALSE, color = "blue", linewidth = 1) +   # ★ 机房版写 size，不写 linewidth
  labs(title = "车重与油耗关系",
       x = "车重", y = "油耗")




