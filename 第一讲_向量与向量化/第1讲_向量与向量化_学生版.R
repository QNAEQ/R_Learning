# ── 9.1　收尾钩子：不写循环，也能求 π ───────────────────────────────────────────────────────
# 只演示，不动手。这是本讲标题里「向量化」三个字的兑现。

# 回合 1 的写法：撒一个点、算一次、判断一次，来回 100 万次
# 我猜：循环与向量化两种写法，哪一种更快？ ____
system.time({                           #system.time函数专门用来测量运行时间
  N <- 1e6; count <- 0
  for (i in 1:N) {
    if (sqrt(runif(1)^2 + runif(1)^2) <= 1) count <- count + 1
  }
  print(count / N * 4)
})

# 向量化写法：一次性撒 100 万个点，一次性判断，一次性求平均
system.time({
  N <- 1e6
  x <- runif(N)                    # 100 万个 x 坐标，一次生成
  y <- runif(N)                    # 100 万个 y 坐标，一次生成
  print(mean(x^2 + y^2 <= 1) * 4)  # 一行算完
})

# 比一比两段代码的行数，再比一比 system.time 报出的耗时。
