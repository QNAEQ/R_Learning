# ── 7.3　★ 把「趋近」这件事画出来 —— 这才是大数定律的样子 ───────────────────────────────────────────



# ┌────────────────────────────────────────────────────────────────────────────┐
# │ ★【练习 7-3】
# 本知识点例题：独立书写；按紧邻的讲解与行尾说明完成。
# └────────────────────────────────────────────────────────────────────────────┘

N <- 5000
和 <- numeric(N)        # 老规矩：先造一个容器，5000个空值，待填充

for (i in 1:N) {    # 【知识点】蒙特卡洛收敛：记录每次试验结果，画收敛曲线
  dice <- sample(1:6, 3, replace = TRUE)
  和[i] <- sum(dice)
}    # 以上结束后，N为一个向量，记录了5000次模拟的和。

# 本题作答与笔记区结束.
累计概率 <- cumsum(和 == 10) / (1:N)          # cumsum = 累积求和（第 1 讲学过）

# 读法：前 i 次里出现了几次「和为 10」，除以 i，就是做到第 i 次时的估计值
#分子为对长度为5000的0/1向量求cumsum，返回5000个值，除以长度为5000的分母，得到一串比值

ggplot(data.frame(次数 = 1:N, 概率 = 累计概率), aes(x = 次数, y = 概率)) +
  geom_line(color = "steelblue") +
  geom_hline(yintercept = 27 / 216, linetype = "dashed", color = "red") +
  labs(title = "三枚骰子点数之和为 10 的概率：模拟值向理论值收敛",
       subtitle = "红色虚线为理论值 27/216 = 0.125",
       x = "模拟次数", y = "累计估计概率") +
  theme_bw()

# ★ 看这张图：前几百次上下乱跳，几千次之后稳稳压在红线上。
#   这就是大数定律。你在《统计学》里背过的那句话，今天亲手把它画了出来。



