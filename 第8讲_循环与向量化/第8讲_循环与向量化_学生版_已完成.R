# ── 6.4　repeat 的一个漂亮用法：生成不超过 1000 的斐波那契数列 ─────────────────────────────────────
# （事先不知道要算几项，正好是 repeat 的主场）



# ┌────────────────────────────────────────────────────────────────────────────┐
# │ ★【练习 6-4】
# 本知识点例题：独立书写；按紧邻的讲解与行尾说明完成。
# └────────────────────────────────────────────────────────────────────────────┘

s <- c(1, 1)
i <- 3
repeat {    # 【知识点】斐波那契数列：repeat适合事先不知道循环次数的场景
  next_fib <- s[i-1] + s[i-2]
  if (next_fib > 1000) break
  s <- c(s, next_fib)
  i <- i + 1
}    # ★ 先判断，再往前走
