# ── 5.1　贷款计算器 ─────────────────────────────────────────────────────────────────
# while 的经典应用：还款要还多少个月？——事先不知道，得一个月一个月算。

# 场景：贷款 30 万，年利率 4.5%，每月还 3000 元，多久能还清？

loan    <- 300000        # 贷款本金
rate    <- 0.045 / 12    # 月利率
payment <- 3000          # 每月还款额
month   <- 0             # 计数器

# ★ 先做一件原版课件没做的事：检查这笔月供到底够不够
cat("第一个月的利息是：", round(loan * rate, 2), "元\n")
cat("你的月供是：", payment, "元\n")
if (payment <= loan * rate) {
  stop("月供还不够付利息，这笔贷款永远还不完 —— 循环会跑到天荒地老。")
}
# ⚠ 这不是杞人忧天。把 payment 改成 1000 试试：月息是 1125 元，
#   你每月还 1000，本金反而每月涨 125。这就是「最低还款额」陷阱的数学本质。
#   写 while 循环，永远要先问一句：这个条件真的会不成立吗？



# ┌────────────────────────────────────────────────────────────────────────────┐
# │ ★【练习 5-1】
# 本知识点例题：独立书写；按紧邻的讲解与行尾说明完成。
# └────────────────────────────────────────────────────────────────────────────┘


while (loan > 0) {    # 【知识点】贷款计算：先计息再还款，用||控制打印
  loan <- loan * (1 + rate) - payment      # 先计息，再还款
  month <- month + 1
  if (month <= 5 || loan <= 0) {            # 只打印前 5 个月和最后一个月
    cat("第", month, "个月，剩余本金：", round(max(loan, 0), 2), "元\n")
  }
}    # 先计息，再还款



