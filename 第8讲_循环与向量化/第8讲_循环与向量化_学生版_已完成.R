# ── 3.1　for 做累积：复利的威力 ─────────────────────────────────────────────────────────
# 这是循环真正不可替代的场景之一：这一年的余额，要用上一年的余额算出来。
# 向量化做不了，因为它没法「一次性」算出一个前后依赖的链条。

# 角色扮演：你是银行的理财经理，客户问你「存 20 年能变多少钱」

input <- 1000              # 初始存入金额
rate  <- 0.05              # 年利率
years <- 20                # 存款年限

# ★ 先「预分配」一个空向量，再往里填 —— 这是循环的标准写法
output <- numeric(years + 1)      # 造一个长度 21、全是 0 的数值向量
output[1] <- input                # 第 0 年（起点）就是本金



# ┌────────────────────────────────────────────────────────────────────────────┐
# │ ★【练习 3-1】
# 本知识点例题：独立书写；按紧邻的讲解与行尾说明完成。
# └────────────────────────────────────────────────────────────────────────────┘


for (i in 1:years) {
  output[i + 1] <- output[i] * (1 + rate)    # 【知识点】复利计算：必须用循环，因为后一年依赖前一年的结果
}    # 这一年 = 上一年 × (1+利率)
#



# 本题作答与笔记区结束.
round(output, 2)

# ⚠ 为什么要先预分配？对比一下这种写法：
#     output <- c();  for (i in 1:years) output <- c(output, ...)
#   每次 c() 都会把整个向量复制一遍再放回去。20 次没感觉，20 万次就卡死了。
#   预分配 = 先把房子盖好再往里搬东西，动态增长 = 每来一件家具就重盖一次房子。

# 画出来（第 5、6 讲学的 ggplot2）
增长 <- data.frame(年份 = 0:years, 余额 = output)
ggplot(增长, aes(x = 年份, y = 余额)) +
  geom_line(color = "steelblue", size = 1) +
  geom_point(size = 2, color = "steelblue") +
  labs(title = paste0("本金 ", input, " 元、年利率 ", rate * 100, "%，", years, " 年后的余额"),
       x = "年份", y = "余额（元）") +
  theme_bw()

# ★ 注意曲线的形状：它不是直线，是往上翘的。这就是复利。
#   前 10 年只涨了 600 多，后 10 年涨了 1000 多 —— 同样是 10 年。

