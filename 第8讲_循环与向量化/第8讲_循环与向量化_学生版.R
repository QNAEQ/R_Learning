while (loan > 0) {  #@ # ____（按本知识点的讲解独立写出代码）
  loan  <- loan * (1 + rate) - payment      # 先计息，再还款  #@ # 先计息，再还款
  month <- month + 1  #@ #
  if (month <= 5 || loan <= 0) {            # 只打印前 5 个月和最后一个月  #@ # 只打印前 5 个月和最后一个月
    cat("第", month, "个月，剩余本金：", round(max(loan, 0), 2), "元\n")  #@ #
  }  #@ #
}  #@ #



cat("\n共需还款", month, "个月，约", round(month / 12, 1), "年\n")
